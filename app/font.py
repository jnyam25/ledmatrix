def glyph(char: str) -> list[str]:
    key = char.upper()
    return _RAW.get(key, _RAW["?"])


def text_width(text: str, scale: int = 1, tracking: int = 1) -> int:
    if not text:
        return 0
    scale = max(1, scale)
    gap = tracking * scale
    return len(text) * (5 * scale) + (len(text) - 1) * gap
